"""Independent DOCX header/footer loss regression; never edits input files.

Fixtures are generated by python-docx, then their header/footer parts are moved
and both OPC content-type overrides and relationships are updated. They are
synthetic targeted fixtures, NOT a real-world corpus. python-docx independently
reopens each package; --render also checks LibreOffice PDF text. The default
expectation is conservative rejection; --expect-baseline-loss demonstrates the
old import/export path losing the independently verified source markers.

Examples (run from the repository root):
  python scripts/check-side-stories.py --cli target/debug/rust-wps --render
  python scripts/check-side-stories.py --cli tmp/old-rust-wps \\
      --expect-baseline-loss --render

Requires python-docx; --render additionally requires LibreOffice and pypdf.
Each run writes fresh files below --root and prints its JSON evidence path.
"""
import argparse
import hashlib
import json
import os
import posixpath
import platform
import shutil
import subprocess
import tempfile
import zipfile
from pathlib import Path
from importlib.metadata import version
# Preserve original namespace prefixes so relocation does not also change the
# OPC XML namespace serialization used by independent readers.
from lxml import etree as ET

from docx import Document

RISK = "Additional document content:"
BODY = [f"BodyProbePage{page}" for page in range(1, 4)]
OFFICE_REL = "http://schemas.openxmlformats.org/officeDocument/2006/relationships/"
WORD_NS = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
ATTRS = {
    "header": {"default": "header", "first": "first_page_header", "even": "even_page_header"},
    "footer": {"default": "footer", "first": "first_page_footer", "even": "even_page_footer"},
}


def check(condition, message):
    # Keep checks active even if the caller runs Python with -O.
    if not condition:
        raise AssertionError(message)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def body_document():
    document = Document()
    for index, marker in enumerate(BODY):
        if index:
            document.add_page_break()
        document.add_paragraph(marker)
    return document


def move_story(source, destination, kind, target):
    """Rename one story without changing the relationship ID or story XML."""
    with zipfile.ZipFile(source) as package:
        parts = {item.filename: (item, package.read(item)) for item in package.infolist()}
    rel_name = "word/_rels/document.xml.rels"
    relationships = ET.fromstring(parts[rel_name][1])
    matching = [rel for rel in relationships if rel.get("Type") == OFFICE_REL + kind]
    check(len(matching) == 1, f"Expected one {kind} relationship")
    relationship = matching[0]
    original = posixpath.normpath("word/" + relationship.get("Target"))
    check(original in parts and target not in parts, "Invalid story relocation")
    relationship.set("Target", posixpath.relpath(target, "word"))
    types = ET.fromstring(parts["[Content_Types].xml"][1])
    matching = [node for node in types if node.get("PartName") == "/" + original]
    check(len(matching) == 1, "Missing original content-type override")
    matching[0].set("PartName", "/" + target)
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED) as output:
        for name, (info, content) in parts.items():
            if name == original:
                output.writestr(target, content)
            elif name == rel_name:
                output.writestr(info, ET.tostring(relationships, encoding="utf-8", xml_declaration=True))
            elif name == "[Content_Types].xml":
                output.writestr(info, ET.tostring(types, encoding="utf-8", xml_declaration=True))
            else:
                output.writestr(info, content)
    return {"original_part": original, "renamed_part": target,
            "relationship_target": relationship.get("Target"),
            "relationship_id": relationship.get("Id"),
            "relationship_type": relationship.get("Type"),
            "content_type": matching[0].get("ContentType")}


def make_fixtures(directory):
    sources = {}
    for kind in ATTRS:
        for variant, attr in ATTRS[kind].items():
            case = f"{kind}-{variant}"
            marker = f"StoryProbe{kind.title()}{variant.title()}"
            document = body_document()
            section = document.sections[0]
            section.different_first_page_header_footer = variant == "first"
            document.settings.odd_and_even_pages_header_footer = variant == "even"
            getattr(section, attr).paragraphs[0].text = marker
            original = directory / f"{case}-original.docx"
            document.save(original)
            path = directory / f"{case}.docx"
            # Exercise nested relative targets and targets outside word/. Names
            # deliberately contain none of the old header/footer substrings.
            target = ("word/auxiliary/story.xml" if kind == "header"
                      else "custom/stories/story.xml")
            moved = move_story(original, path, kind, target)
            reopened = Document(path)
            independent_text = "\n".join(p.text for p in getattr(reopened.sections[0], attr).paragraphs)
            check(independent_text == marker, f"python-docx lost {case} source marker")
            check(all(value in "\n".join(p.text for p in reopened.paragraphs) for value in BODY),
                  f"python-docx lost {case} source body")
            with zipfile.ZipFile(path) as package:
                check(moved["original_part"] not in package.namelist(), "Old part retained")
                check(not any("header" in name or "footer" in name for name in package.namelist()),
                      "Fixture accidentally retains a filename recognized by the old audit")
                main = ET.fromstring(package.read("word/document.xml"))
                refs = main.findall(f".//{{{WORD_NS}}}{kind}Reference")
                check(len(refs) == 1 and refs[0].get(f"{{{WORD_NS}}}type") == variant,
                      f"Wrong section reference for {case}")
            sources[case] = {"path": str(path), "sha256": digest(path), "marker": marker,
                             "kind": kind, "reference_type": variant,
                             "independent_story_text": independent_text, **moved}
    path = directory / "simple.docx"
    body_document().save(path)
    sources["simple"] = {"path": str(path), "sha256": digest(path)}
    return sources


def run_cli(cli, log, *args, success=True):
    process = subprocess.run([str(cli), *map(str, args)], text=True, capture_output=True,
                             timeout=60, encoding="utf-8")
    log.append({"arguments": list(map(str, args)), "returncode": process.returncode,
                "stdout": process.stdout, "stderr": process.stderr})
    check((process.returncode == 0) is success, process.stdout + process.stderr)
    return json.loads(process.stdout) if success else process.stderr


def text_and_structure(node):
    """Ignore known style normalization while comparing content and page breaks."""
    return (node["type"], node.get("text"),
            [text_and_structure(child) for child in node.get("content", [])])


def all_story_text(document):
    return "\n".join(paragraph.text for section in document.sections
                     for attrs in ATTRS.values() for attr in attrs.values()
                     for paragraph in getattr(section, attr).paragraphs)


def render_pdf(soffice, directory, path):
    from pypdf import PdfReader
    out = directory / "rendered"
    out.mkdir(exist_ok=True)
    # A unique profile prevents an unrelated running GUI instance from taking
    # ownership of the conversion and returning before its output exists.
    profile = directory / "lo-profile"
    environment = dict(os.environ, XDG_CACHE_HOME=str(directory / "lo-cache"))
    process = subprocess.run([str(soffice), f"-env:UserInstallation={profile.as_uri()}",
                              "--headless", "--convert-to", "pdf", "--outdir", str(out), str(path)],
                             text=True, capture_output=True, timeout=120, encoding="utf-8", env=environment)
    pdf = out / (path.stem + ".pdf")
    check(process.returncode == 0 and pdf.is_file(), process.stdout + process.stderr)
    pages = [page.extract_text() or "" for page in PdfReader(pdf).pages]
    return {"pdf": str(pdf), "pdf_sha256": digest(pdf), "pages": pages,
            "conversion_stdout": process.stdout, "conversion_stderr": process.stderr}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cli", type=Path, default=Path("target/debug/rust-wps"))
    parser.add_argument("--root", type=Path, default=Path("tmp/side-stories"))
    parser.add_argument("--expect-baseline-loss", action="store_true")
    parser.add_argument("--render", action="store_true")
    parser.add_argument("--soffice", help="LibreOffice executable (otherwise found on PATH)")
    args = parser.parse_args()
    cli = args.cli.resolve()
    check(cli.is_file(), f"CLI not found: {cli}")
    soffice = args.soffice or shutil.which("soffice")
    if args.render:
        check(soffice, "LibreOffice is required for --render")
    args.root.mkdir(parents=True, exist_ok=True)
    directory = Path(tempfile.mkdtemp(prefix="run-", dir=args.root)).resolve()
    evidence = {"fixture_kind": "Generated targeted python-docx packages, NOT real-world corpus",
                "baseline_loss_expected": args.expect_baseline_loss,
                "script_sha256": digest(Path(__file__)),
                "cli": str(cli), "cli_sha256": digest(cli), "render_requested": args.render,
                "python_version": platform.python_version(), "python_docx_version": version("python-docx"),
                "lxml_version": version("lxml"),
                "status": "running", "sources": {}, "commands": [],
                "limitations": "Checks semantic source markers and selected default/first/even story visibility. "
                "Not Microsoft Word/WPS or native WebView2 validation, a full layout oracle, "
                "or support for editing header/footer content. No real-world corpus is claimed."}
    report = directory / "report.json"
    log = evidence["commands"]
    try:
        if args.render:
            evidence["pypdf_version"] = version("pypdf")
            evidence["libreoffice_version"] = subprocess.run(
                [str(soffice), "--version"], check=True, capture_output=True,
                text=True, timeout=30).stdout.strip()
        evidence["sources"] = make_fixtures(directory)
        for case, source in evidence["sources"].items():
            path = Path(source["path"])
            audit = run_cli(cli, log, "audit-docx", path)
            source["audit"] = audit
            marker = source.get("marker")
            if marker and not args.expect_baseline_loss:
                check(any(risk.startswith(RISK) for risk in audit["risks"]),
                      f"Missing additional-content risk: {case}")
                source["import_error"] = run_cli(cli, log, "import-docx", path, success=False)
                check(RISK in source["import_error"], f"Wrong import refusal: {case}")
            else:
                if marker:
                    check(not any(risk.startswith(RISK) for risk in audit["risks"]),
                          f"Baseline unexpectedly detects {case}")
                imported = run_cli(cli, log, "import-docx", path)
                serialized = json.dumps(imported["document"])
                check(all(value in serialized for value in BODY), f"Missing imported body: {case}")
                if marker:
                    check(marker not in serialized, f"Baseline unexpectedly preserves {case}")
                model = directory / f"{case}.json"
                model.write_text(json.dumps(imported["document"]), encoding="utf-8")
                output = directory / f"{case}-export.docx"
                run_cli(cli, log, "create-docx", model, output)
                independent = Document(output)
                independent_body = "\n".join(p.text for p in independent.paragraphs)
                independent_stories = all_story_text(independent)
                check(all(value in independent_body for value in BODY), f"Missing exported body: {case}")
                if marker:
                    check(marker not in independent_body + independent_stories,
                          f"Baseline export unexpectedly preserves {case}")
                reopened = run_cli(cli, log, "import-docx", output)
                check(text_and_structure(reopened["document"]) == text_and_structure(imported["document"]),
                      f"Reopened content or structure changed: {case}")
                source.update(export_path=str(output), export_sha256=digest(output),
                              export_independent_body=independent_body,
                              export_independent_story_text=independent_stories,
                              reopened_content_and_structure_equal=True,
                              reopened_model_equal=reopened["document"] == imported["document"])
                source["overwrite_error"] = run_cli(cli, log, "create-docx", model, output, success=False)
                check("Output already exists" in source["overwrite_error"], "Wrong overwrite refusal")
                check(digest(output) == source["export_sha256"], "Existing output changed")
                source["source_overwrite_error"] = run_cli(cli, log, "create-docx", model, path, success=False)
                source["overwrite_refused"] = True
                # Use this known-good model below against all existing sources.
                if case == "simple":
                    simple_model = model
                if args.render:
                    source["export_render"] = render_pdf(soffice, directory, output)
                    text = "\n".join(source["export_render"]["pages"])
                    check(all(value in text for value in BODY), "Export PDF lost body")
                    if marker:
                        check(marker not in text, "Baseline PDF unexpectedly preserves story")
            if args.render:
                source["source_render"] = render_pdf(soffice, directory, path)
                pages = source["source_render"]["pages"]
                check(len(pages) == 3, f"Expected three source pages: {case}")
                check(all(value in "\n".join(pages) for value in BODY), "Source PDF lost body")
                if marker:
                    expected_pages = {"default": [0, 1, 2], "first": [0], "even": [1]}[source["reference_type"]]
                    actual_pages = [index for index, text in enumerate(pages) if marker in text]
                    check(actual_pages == expected_pages, f"Wrong story PDF pages for {case}: {actual_pages}")
                    source["source_render"]["marker_page_numbers"] = [index + 1 for index in actual_pages]
            check(digest(path) == source["sha256"], f"Source changed: {case}")
        for source in evidence["sources"].values():
            path = Path(source["path"])
            source["source_overwrite_error"] = run_cli(cli, log, "create-docx", simple_model, path, success=False)
            check("Output already exists" in source["source_overwrite_error"], "Wrong source overwrite refusal")
            check(digest(path) == source["sha256"], f"Source changed: {path}")
            source["source_unchanged"] = True
            source["source_overwrite_refused"] = True
        evidence["status"] = "passed"
    except Exception as error:
        evidence["status"] = "failed"
        evidence["error"] = f"{type(error).__name__}: {error}"
        raise
    finally:
        report.write_text(json.dumps(evidence, ensure_ascii=False, indent=2), encoding="utf-8")
        print(report)


if __name__ == "__main__":
    main()

#[derive(Debug, Clone, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Node {
    #[serde(rename = "type")]
    pub kind: String,
    #[serde(default, skip_serializing_if = "Map::is_empty")]
    pub attrs: Map<String, Value>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub content: Vec<Node>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text: Option<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub marks: Vec<Mark>,
}

#[derive(Debug, Clone, PartialEq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Mark {
    #[serde(rename = "type")]
    pub kind: String,
    #[serde(default, skip_serializing_if = "Map::is_empty")]
    pub attrs: Map<String, Value>,
}

pub fn supported_link(href: &str) -> bool {
    let lower = href.to_ascii_lowercase();
    href.len() <= 2048
        && !href.chars().any(|c| c.is_control() || c.is_whitespace())
        && xml_text(href)
        && ["https://", "http://", "mailto:"]
            .iter()
            .any(|prefix| lower.starts_with(prefix) && href.len() > prefix.len())
}

/// One literal font family, not a CSS fallback list. Word restricts rFonts
/// names to fewer than 32 characters; use UTF-16 units for the Windows limit.
pub fn supported_font_family(name: &str) -> bool {
    !name.is_empty()
        && name.encode_utf16().count() <= 31
        && name.trim_matches(|c: char| c.is_whitespace() || c == '\u{feff}') == name
        && !name.chars().any(char::is_control)
        && xml_text(name)
}


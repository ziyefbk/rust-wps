/// Immutable default-style contract for newly authored documents. Changing
/// these defaults requires a new profile so existing packages still reencode.
pub const STANDARD_STYLE_PROFILE: &str = "standard-v2";
const MODEL_PART_V1: &str = "rust-wps/model-v1.json";
const MODEL_PART_V2: &str = "rust-wps/model-v2.json";

#[derive(Clone, Copy, Default, PartialEq, Eq)]
enum StyleProfile {
    #[default]
    LegacyV1,
    StandardV2,
}

impl StyleProfile {
    fn version(self) -> u32 {
        match self {
            Self::LegacyV1 => 1,
            Self::StandardV2 => 2,
        }
    }

    fn model_part(self) -> &'static str {
        match self {
            Self::LegacyV1 => MODEL_PART_V1,
            Self::StandardV2 => MODEL_PART_V2,
        }
    }
}

fn style_profile(doc: &Node) -> Result<StyleProfile> {
    match doc.attrs.get("styleProfile") {
        None => Ok(StyleProfile::LegacyV1),
        Some(Value::String(value)) if value == STANDARD_STYLE_PROFILE => {
            Ok(StyleProfile::StandardV2)
        }
        _ => bail!("Style profile must be omitted or standard-v2"),
    }
}

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct EmbeddedModel {
    version: u32,
    document: Node,
    hashes: std::collections::BTreeMap<String, String>,
}

/// Reopen documents generated by this application only when every package part
/// still matches its embedded model. External modifications never get silently
/// discarded by loading an out-of-date model.
pub fn load_authored_docx(path: &Path) -> Result<Option<Node>> {
    use std::io::Read;
    let mut bytes = Vec::new();
    std::fs::File::open(path)?
        .take(64 * 1024 * 1024 + 1)
        .read_to_end(&mut bytes)?;
    ensure!(bytes.len() <= 64 * 1024 * 1024, "Input exceeds 64 MiB");
    let zip = zip::ZipArchive::new(Cursor::new(&bytes))?;
    let model_parts = zip
        .file_names()
        .filter(|name| name.starts_with("rust-wps/model-v") && name.ends_with(".json"))
        .collect::<Vec<_>>();
    ensure!(
        model_parts.len() <= 1,
        "DOCX contains multiple authoring models"
    );
    let Some(&model_part) = model_parts.first() else {
        return Ok(None);
    };
    let part_version = match model_part {
        MODEL_PART_V1 => 1,
        MODEL_PART_V2 => 2,
        _ => bail!("Unsupported authoring model part: {model_part}"),
    };
    let parts = crate::editing::parts(&bytes)?;
    let metadata = parts.get(model_part).context("Missing authoring model")?;
    ensure!(
        metadata.len() <= 32 * 1024 * 1024,
        "Embedded model exceeds limits"
    );
    let embedded: EmbeddedModel = serde_json::from_slice(metadata)?;
    ensure!(
        matches!(embedded.version, 1 | 2),
        "Unsupported embedded model version"
    );
    validate(&embedded.document)?;
    ensure!(
        embedded.version == part_version
            && embedded.version == style_profile(&embedded.document)?.version(),
        "Embedded model version, profile and part name disagree"
    );
    ensure!(
        embedded
            .hashes
            .keys()
            .eq(parts.keys().filter(|name| name.as_str() != model_part)),
        "DOCX parts changed outside the authoring model"
    );
    for (name, expected) in &embedded.hashes {
        let data = parts.get(name).context("DOCX part removed")?;
        ensure!(
            format!("{:x}", Sha256::digest(data)) == *expected,
            "DOCX was modified outside the authoring model: {name}"
        );
    }
    // Hashes alone do not bind metadata to its contents: a model-only edit
    // leaves the package hashes unchanged. Re-encode and compare the complete
    // supported package representation before enabling direct editing.
    let (expected, _) = encode_docx(&embedded.document)?;
    let expected = crate::editing::parts(&expected)?;
    ensure!(
        expected.keys().eq(parts.keys()),
        "Embedded model disagrees with DOCX part set"
    );
    for (name, data) in &parts {
        if name != model_part {
            ensure!(
                expected.get(name) == Some(data),
                "Embedded model disagrees with DOCX content: {name}"
            );
        }
    }
    Ok(Some(embedded.document))
}

pub fn save_draft(doc: &Node, path: &Path) -> Result<()> {
    validate(doc)?;
    let bytes = serde_json::to_vec(&Draft {
        version: style_profile(doc)?.version(),
        document: doc.clone(),
    })?;
    ensure!(bytes.len() <= 32 * 1024 * 1024, "Draft exceeds 32 MiB");
    let parent = path.parent().context("Draft path needs a directory")?;
    std::fs::create_dir_all(parent)?;
    let mut temp = tempfile::NamedTempFile::new_in(parent)?;
    temp.write_all(&bytes)?;
    temp.as_file().sync_all()?;
    temp.persist(path)
        .map_err(|e| anyhow::anyhow!("Cannot save draft: {}", e.error))?;
    Ok(())
}

pub fn load_draft(path: &Path) -> Result<Option<Node>> {
    use std::io::Read;
    let file = match std::fs::File::open(path) {
        Ok(file) => file,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(error) => return Err(error.into()),
    };
    let mut bytes = Vec::new();
    file.take(32 * 1024 * 1024 + 1).read_to_end(&mut bytes)?;
    ensure!(bytes.len() <= 32 * 1024 * 1024, "Draft exceeds 32 MiB");
    let draft: Draft = serde_json::from_slice(&bytes)?;
    ensure!(matches!(draft.version, 1 | 2), "Unsupported draft version");
    validate(&draft.document)?;
    ensure!(
        draft.version == style_profile(&draft.document)?.version(),
        "Draft version disagrees with document style profile"
    );
    Ok(Some(draft.document))
}

fn escaped(text: &str) -> String {
    quick_xml::escape::escape(text).into_owned()
}
fn xml_text(text: &str) -> bool {
    text.chars().all(|c| matches!(c, '\t' | '\n' | '\r' | '\u{20}'..='\u{d7ff}' | '\u{e000}'..='\u{fffd}' | '\u{10000}'..='\u{10ffff}'))
}
fn integer(node: &Node, key: &str, default: u64) -> Result<u64> {
    node.attrs.get(key).map_or(Ok(default), |v| {
        v.as_u64()
            .with_context(|| format!("{key} must be a positive integer"))
    })
}
fn is_block(kind: &str) -> bool {
    matches!(
        kind,
        "paragraph" | "heading" | "bulletList" | "orderedList" | "table" | "image"
    )
}

/// Product limit shared by the editor and import audit, not the OOXML maximum.
pub const MAX_TABLE_WIDTH_TWIPS: u64 = 31680;

/// Optional explicit single-section page geometry. Absence retains the exact
/// historical V1/V2 page and print contracts; recognition never rounds values.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct PageGeometry {
    pub width_twips: u64,
    pub height_twips: u64,
    pub margin_top_twips: u64,
    pub margin_right_twips: u64,
    pub margin_bottom_twips: u64,
    pub margin_left_twips: u64,
}

pub fn validate_page_geometry(page: &PageGeometry) -> Result<()> {
    let recognized = [(11906u64, 16838u64), (12240, 15840), (8391, 11906)]
        .into_iter()
        .any(|(width, height)| {
            (page.width_twips.abs_diff(width) <= 2 && page.height_twips.abs_diff(height) <= 2)
                || (page.width_twips.abs_diff(height) <= 2
                    && page.height_twips.abs_diff(width) <= 2)
        });
    ensure!(
        recognized,
        "Page size is outside supported A4, Letter and A5 bounds"
    );
    ensure!(
        [
            page.margin_top_twips,
            page.margin_right_twips,
            page.margin_bottom_twips,
            page.margin_left_twips
        ]
        .into_iter()
        .all(|margin| margin <= 4320),
        "Page margins must be integer twips in 0..=4320"
    );
    ensure!(
        page.margin_left_twips + page.margin_right_twips + 1440 <= page.width_twips
            && page.margin_top_twips + page.margin_bottom_twips + 1440 <= page.height_twips,
        "Page content area must be at least 1440 twips in each direction"
    );
    Ok(())
}

pub fn page_geometry(doc: &Node) -> Result<Option<PageGeometry>> {
    let Some(value) = doc.attrs.get("pageGeometry") else {
        return Ok(None);
    };
    let geometry: PageGeometry = serde_json::from_value(value.clone())
        .context("Page geometry requires exactly six integer-twip fields")?;
    validate_page_geometry(&geometry)?;
    Ok(Some(geometry))
}

/// Check bounded object frames, not text pagination or intrinsic auto-table
/// layout. Legacy explicit-left-indent tables can protrude 108 twips left;
/// this conservative size/right-edge check does not promise full containment.
fn validate_page_content(doc: &Node, page: &PageGeometry) -> Result<()> {
    let width = page.width_twips - page.margin_left_twips - page.margin_right_twips;
    let height = page.height_twips - page.margin_top_twips - page.margin_bottom_twips;
    let mut stack = vec![(doc, 0usize)];
    while let Some((node, depth)) = stack.pop() {
        if node.kind == "table" {
            ensure!(
                depth == 1,
                "Explicit page geometry supports only top-level tables"
            );
            let total = table_layout_width(node, Some(page))?;
            let (_, indent) = table_position(node)?;
            ensure!(
                total + indent.unwrap_or(0) <= width,
                "Table width and indentation exceed the explicit page content width; resize it explicitly first"
            );
        } else if node.kind == "image" {
            let source = node.attrs["src"].as_str().context("Missing image source")?;
            let (header, encoded) = source.split_once(',').context("Invalid embedded image")?;
            let mime = header
                .strip_prefix("data:")
                .and_then(|s| s.strip_suffix(";base64"))
                .context("Invalid image MIME")?;
            let bytes = base64::engine::general_purpose::STANDARD
                .decode(encoded)
                .context("Invalid image base64")?;
            validate_image_display_media(mime, &bytes)?;
            let dimensions = if let Some(dimensions) = image_display_dimensions(node)? {
                dimensions
            } else {
                let format = if mime == "image/png" {
                    image::ImageFormat::Png
                } else {
                    image::ImageFormat::Jpeg
                };
                let (pixels_w, pixels_h) =
                    image::ImageReader::with_format(Cursor::new(&bytes), format)
                        .into_dimensions()
                        .context("Invalid image dimensions")?;
                let scale = (600.0 / f64::from(pixels_w))
                    .min(1.0)
                    .min(800.0 / f64::from(pixels_h));
                (
                    (f64::from(pixels_w) * scale * 9525.0).round() as u64,
                    (f64::from(pixels_h) * scale * 9525.0).round() as u64,
                )
            };
            ensure!(
                dimensions.0 <= width * 635 && dimensions.1 <= height * 635,
                "Image frame exceeds the explicit page content area; resize it explicitly first"
            );
        }
        stack.extend(node.content.iter().map(|child| (child, depth + 1)));
    }
    Ok(())
}

/// Canonical image display geometry, in English Metric Units (914400/inch).
/// These fit the standard A4 content box and keep the historical 600x800px
/// authoring ceiling. Pixel dimensions and original media bytes are separate.
pub const MAX_IMAGE_WIDTH_EMU: u64 = 5_715_000;
pub const MAX_IMAGE_HEIGHT_EMU: u64 = 7_620_000;

pub fn image_display_dimensions(node: &Node) -> Result<Option<(u64, u64)>> {
    match (
        node.attrs.get("displayWidthEmu"),
        node.attrs.get("displayHeightEmu"),
    ) {
        (None, None) => Ok(None),
        (Some(width), Some(height)) => {
            let width = width
                .as_u64()
                .context("Image display width must be integer EMU")?;
            let height = height
                .as_u64()
                .context("Image display height must be integer EMU")?;
            ensure!(
                (1..=MAX_IMAGE_WIDTH_EMU).contains(&width)
                    && (1..=MAX_IMAGE_HEIGHT_EMU).contains(&height),
                "Image display dimensions exceed supported bounds"
            );
            Ok(Some((width, height)))
        }
        _ => bail!("Image display width and height must be supplied together"),
    }
}

/// Complete optional paragraph metadata. Omission keeps the historic image
/// encoding path; explicit null and partial font pairs are never defaults.
pub(crate) fn image_paragraph(
    node: &Node,
) -> Result<Option<crate::image_dimensions::ImageParagraph>> {
    let Some(value) = node.attrs.get("imageParagraph") else {
        return Ok(None);
    };
    let object = value
        .as_object()
        .context("Image paragraph must be an object; omit it for the default")?;
    for key in ["paragraphFont", "runFont"] {
        ensure!(
            object.get(key).is_none_or(|value| value.is_object()),
            "Image paragraph fonts must be objects, not null"
        );
    }
    ensure!(
        object.contains_key("paragraphFont") == object.contains_key("runFont"),
        "Image paragraph fonts must be supplied together"
    );
    let paragraph: crate::image_dimensions::ImageParagraph =
        serde_json::from_value(value.clone()).context("Invalid image paragraph metadata")?;
    ensure!(
        paragraph.space_before <= 31680
            && paragraph.space_after <= 31680
            && (120..=2400).contains(&paragraph.line_spacing),
        "Image paragraph spacing exceeds supported bounds"
    );
    ensure!(
        matches!(
            paragraph.text_align.as_str(),
            "left" | "center" | "right" | "justify"
        ),
        "Unsupported image paragraph alignment"
    );
    for font in [&paragraph.paragraph_font, &paragraph.run_font]
        .into_iter()
        .flatten()
    {
        ensure!(
            supported_font_family(&font.family) && (2..=3276).contains(&font.half_points),
            "Invalid image paragraph font metrics"
        );
    }
    Ok(Some(paragraph))
}

/// The new display-size subset excludes orientation/animation metadata whose
/// interpretation differs between browser and Office consumers. We keep bytes
/// intact, so stripping such metadata is not an acceptable silent fallback.
pub(crate) fn validate_image_display_media(mime: &str, data: &[u8]) -> Result<()> {
    ensure!(
        !data.is_empty() && data.len() <= 8 * 1024 * 1024,
        "Image blob exceeds 8 MiB"
    );
    let format = match mime {
        "image/png" => image::ImageFormat::Png,
        "image/jpeg" => image::ImageFormat::Jpeg,
        _ => bail!("Only displayed PNG/JPEG images are supported"),
    };
    let (width, height) = image::ImageReader::with_format(Cursor::new(data), format)
        .into_dimensions()
        .context("Invalid displayed image header")?;
    ensure!(
        width > 0
            && height > 0
            && width <= 20000
            && height <= 20000
            && u64::from(width) * u64::from(height) <= 40_000_000,
        "Image pixel dimensions exceed limits"
    );
    match mime {
        "image/png" => {
            ensure!(
                data.starts_with(b"\x89PNG\r\n\x1a\n"),
                "Invalid displayed PNG signature"
            );
            let mut offset = 8;
            while offset < data.len() {
                ensure!(data.len() - offset >= 12, "Truncated PNG chunk");
                let size = u32::from_be_bytes(data[offset..offset + 4].try_into()?) as usize;
                ensure!(size <= data.len() - offset - 12, "Truncated PNG chunk data");
                let tag = &data[offset + 4..offset + 8];
                ensure!(
                    !matches!(tag, b"eXIf" | b"acTL" | b"fcTL" | b"fdAT"),
                    "Displayed PNG orientation metadata and animation are unsupported"
                );
                offset += size + 12;
                if tag == b"IEND" {
                    ensure!(
                        size == 0 && offset == data.len(),
                        "Unexpected data after PNG IEND"
                    );
                    return Ok(());
                }
            }
            bail!("PNG has no complete IEND")
        }
        "image/jpeg" => {
            ensure!(
                data.starts_with(&[0xff, 0xd8]),
                "Invalid displayed JPEG signature"
            );
            let mut offset = 2;
            let mut entropy = false;
            while offset < data.len() {
                if entropy {
                    while offset < data.len() && data[offset] != 0xff {
                        offset += 1;
                    }
                }
                ensure!(
                    offset < data.len() && data[offset] == 0xff,
                    "Malformed JPEG marker"
                );
                while offset < data.len() && data[offset] == 0xff {
                    offset += 1;
                }
                let marker = *data.get(offset).context("Truncated JPEG marker")?;
                offset += 1;
                if entropy && (marker == 0 || (0xd0..=0xd7).contains(&marker)) {
                    continue;
                }
                ensure!(
                    marker != 0xe1,
                    "Displayed JPEG APP1 orientation metadata is unsupported"
                );
                if marker == 0xd9 {
                    ensure!(offset == data.len(), "Unexpected data after JPEG EOI");
                    return Ok(());
                }
                ensure!(
                    !matches!(marker, 0 | 0x01 | 0xd0..=0xd8),
                    "Unsupported JPEG marker"
                );
                ensure!(data.len() - offset >= 2, "Truncated JPEG segment");
                let size = u16::from_be_bytes(data[offset..offset + 2].try_into()?) as usize;
                ensure!(
                    size >= 2 && size <= data.len() - offset,
                    "Invalid JPEG segment length"
                );
                offset += size;
                entropy = marker == 0xda;
            }
            bail!("JPEG has no complete EOI")
        }
        _ => bail!("Only displayed PNG/JPEG images are supported"),
    }
}

pub fn table_column_widths(node: &Node) -> Result<Option<Vec<u64>>> {
    let Some(value) = node.attrs.get("columnWidthsTwips") else {
        return Ok(None);
    };
    let values = value
        .as_array()
        .context("Table columnWidthsTwips must be an integer array")?;
    let columns = node.content.first().map_or(0, |row| row.content.len());
    ensure!(
        values.len() == columns && columns > 0,
        "Table column width count must match its columns"
    );
    let mut widths = Vec::with_capacity(values.len());
    let mut total = 0u64;
    for value in values {
        let width = value
            .as_u64()
            .context("Table column widths must be positive integers")?;
        ensure!(
            (1..=MAX_TABLE_WIDTH_TWIPS).contains(&width),
            "Table column width exceeds limits"
        );
        total += width;
        ensure!(
            total <= MAX_TABLE_WIDTH_TWIPS,
            "Total table width exceeds limits"
        );
        widths.push(width);
    }
    Ok(Some(widths))
}

/// Optional positioning is separate from paragraph alignment. Omission retains
/// legacy encoding; explicit zero is retained rather than treated as absent.
pub fn table_position(node: &Node) -> Result<(Option<&str>, Option<u64>)> {
    let alignment = node
        .attrs
        .get("tableAlign")
        .map(|value| {
            let value = value.as_str().context("Table alignment must be a string")?;
            ensure!(
                matches!(value, "left" | "center" | "right"),
                "Unsupported table alignment"
            );
            Ok::<_, anyhow::Error>(value)
        })
        .transpose()?;
    let indent = node
        .attrs
        .get("tableIndentTwips")
        .map(|value| {
            let value = value
                .as_u64()
                .context("Table indent must be integer twips")?;
            ensure!(
                value <= MAX_TABLE_WIDTH_TWIPS,
                "Table indent exceeds limits"
            );
            Ok::<_, anyhow::Error>(value)
        })
        .transpose()?;
    ensure!(
        indent.unwrap_or(0) == 0 || alignment.is_none_or(|a| a == "left"),
        "Positive table indentation requires left alignment"
    );
    if indent.is_some() {
        let total = table_column_widths(node)?.map_or(9000, |widths| widths.iter().sum());
        ensure!(
            total + indent.unwrap_or(0) <= MAX_TABLE_WIDTH_TWIPS,
            "Table width and indentation exceed limits"
        );
    }
    Ok((alignment, indent))
}

/// Only automatic tables without any explicit position metadata reflow to a
/// smaller explicit page. Their width was already an authored normalization,
/// never a preserved source width. Fixed/positioned geometry is not rescaled.
pub fn table_layout_width(node: &Node, page: Option<&PageGeometry>) -> Result<u64> {
    if let Some(widths) = table_column_widths(node)? {
        return Ok(widths.iter().sum());
    }
    let (alignment, indent) = table_position(node)?;
    if alignment.is_none()
        && indent.is_none()
        && let Some(page) = page
    {
        validate_page_geometry(page)?;
        return Ok(9000.min(page.width_twips - page.margin_left_twips - page.margin_right_twips));
    }
    Ok(9000)
}

pub fn validate(doc: &Node) -> Result<()> {
    ensure!(doc.kind == "doc", "Root must be doc");
    style_profile(doc)?;
    let page = page_geometry(doc)?;
    let mut nodes = 0usize;
    let mut text_bytes = 0usize;
    fn visit(
        node: &Node,
        depth: usize,
        table_depth: usize,
        fixed_ancestor: bool,
        nodes: &mut usize,
        text_bytes: &mut usize,
    ) -> Result<()> {
        *nodes += 1;
        ensure!(
            *nodes <= 10000 && depth <= 32,
            "Document structure exceeds limits"
        );
        let allowed: &[&str] = match node.kind.as_str() {
            "doc" if depth == 0 => &["styleProfile", "pageGeometry"],
            "heading" => &[
                "level",
                "textAlign",
                "spaceBefore",
                "spaceAfter",
                "lineSpacing",
            ],
            "paragraph" => &["textAlign", "spaceBefore", "spaceAfter", "lineSpacing"],
            "orderedList" => &["start", "type"],
            "table" => &["columnWidthsTwips", "tableAlign", "tableIndentTwips"],
            "tableCell" | "tableHeader" => &["colspan", "rowspan", "colwidth", "align"],
            "image" => &[
                "src",
                "alt",
                "title",
                "width",
                "height",
                "displayWidthEmu",
                "displayHeightEmu",
                "imageParagraph",
            ],
            "doc" | "text" | "hardBreak" | "pageBreak" | "bulletList" | "listItem" | "tableRow" => {
                &[]
            }
            other => bail!("Unsupported document node: {other}"),
        };
        for key in node.attrs.keys() {
            ensure!(
                allowed.contains(&key.as_str()),
                "Unsupported {} attribute: {key}",
                node.kind
            );
        }
        if let Some(alignment) = node.attrs.get("textAlign").filter(|v| !v.is_null()) {
            ensure!(
                matches!(
                    alignment.as_str(),
                    Some("left" | "center" | "right" | "justify")
                ),
                "Unsupported paragraph alignment"
            );
        }
        for (key, minimum, maximum) in [
            ("spaceBefore", 0, 31680),
            ("spaceAfter", 0, 31680),
            ("lineSpacing", 120, 2400),
        ] {
            if let Some(value) = node.attrs.get(key) {
                ensure!(
                    value
                        .as_u64()
                        .is_some_and(|value| (minimum..=maximum).contains(&value)),
                    "{key} must be an integer in {minimum}..={maximum}; omit it for the default"
                );
            }
        }
        ensure!(
            node.kind == "text" || node.text.is_none(),
            "Only text nodes may contain text"
        );
        ensure!(
            node.kind == "text" || node.marks.is_empty(),
            "Marks require text nodes"
        );
        ensure!(
            node.marks
                .iter()
                .filter(|mark| matches!(mark.kind.as_str(), "superscript" | "subscript"))
                .count()
                <= 1,
            "Text cannot have conflicting or duplicate script marks"
        );
        ensure!(
            node.marks
                .iter()
                .filter(|mark| mark.kind == "fontSize")
                .count()
                <= 1,
            "Text may have only one font size"
        );
        ensure!(
            node.marks
                .iter()
                .filter(|mark| mark.kind == "textColor")
                .count()
                <= 1,
            "Text may have only one text color"
        );
        ensure!(
            node.marks
                .iter()
                .filter(|mark| mark.kind == "fontFamily")
                .count()
                <= 1,
            "Text may have only one font family"
        );
        for mark in &node.marks {
            ensure!(
                matches!(
                    mark.kind.as_str(),
                    "bold"
                        | "italic"
                        | "underline"
                        | "strike"
                        | "code"
                        | "link"
                        | "superscript"
                        | "subscript"
                        | "fontSize"
                        | "textColor"
                        | "fontFamily"
                ),
                "Unsupported mark: {}",
                mark.kind
            );
            if mark.kind == "link" {
                ensure!(
                    mark.attrs
                        .get("href")
                        .and_then(Value::as_str)
                        .is_some_and(supported_link),
                    "Unsupported link target; use HTTP, HTTPS or mailto"
                );
                for (key, value) in &mark.attrs {
                    ensure!(
                        matches!(key.as_str(), "href" | "target" | "rel" | "class" | "title")
                            && (value.is_null()
                                || value
                                    .as_str()
                                    .is_some_and(|s| s.len() <= 2048 && xml_text(s))),
                        "Unsupported link attribute"
                    );
                }
            } else if mark.kind == "fontSize" {
                ensure!(
                    mark.attrs.len() == 1
                        && mark
                            .attrs
                            .get("halfPoints")
                            .and_then(Value::as_u64)
                            .is_some_and(|value| (2..=3276).contains(&value)),
                    "Font size requires integer halfPoints between 2 and 3276"
                );
            } else if mark.kind == "textColor" {
                ensure!(
                    mark.attrs.len() == 1
                        && mark
                            .attrs
                            .get("rgb")
                            .and_then(Value::as_str)
                            .is_some_and(|rgb| {
                                rgb.len() == 6
                                    && rgb.bytes().all(|byte| {
                                        byte.is_ascii_digit() || matches!(byte, b'A'..=b'F')
                                    })
                            }),
                    "Text color requires rgb with exactly six uppercase hexadecimal characters"
                );
            } else if mark.kind == "fontFamily" {
                ensure!(
                    mark.attrs.len() == 1
                        && mark
                            .attrs
                            .get("name")
                            .and_then(Value::as_str)
                            .is_some_and(supported_font_family),
                    "Font family requires one literal name of 1–31 UTF-16 units without outer whitespace or control characters"
                );
            } else {
                ensure!(
                    mark.attrs.is_empty(),
                    "Attributes require a link, font size, text color or font family mark"
                );
            }
        }
        ensure!(
            node.marks.iter().filter(|m| m.kind == "link").count() <= 1,
            "Text may have only one link"
        );
        let valid_child = |child: &Node| match node.kind.as_str() {
            "doc" => is_block(&child.kind) || child.kind == "pageBreak",
            "listItem" | "tableCell" | "tableHeader" => is_block(&child.kind),
            "paragraph" | "heading" => matches!(child.kind.as_str(), "text" | "hardBreak"),
            "bulletList" | "orderedList" => child.kind == "listItem",
            "table" => child.kind == "tableRow",
            "tableRow" => matches!(child.kind.as_str(), "tableCell" | "tableHeader"),
            _ => false,
        };
        ensure!(
            node.content.iter().all(valid_child),
            "Invalid child in {}",
            node.kind
        );
        if !matches!(
            node.kind.as_str(),
            "paragraph" | "heading" | "text" | "hardBreak" | "pageBreak" | "image"
        ) {
            ensure!(!node.content.is_empty(), "{} must not be empty", node.kind);
        }
        if node.kind == "text" {
            let text = node.text.as_deref().context("Missing text")?;
            ensure!(xml_text(text), "Text contains illegal XML characters");
            *text_bytes += text.len();
            ensure!(*text_bytes <= 2 * 1024 * 1024, "Text exceeds 2 MiB");
        }
        if node.kind == "heading" {
            ensure!(
                (1..=3).contains(&integer(node, "level", 1)?),
                "Heading level must be 1–3"
            );
        }
        if node.kind == "image" {
            let dimensions = image_display_dimensions(node)?;
            let paragraph = image_paragraph(node)?;
            ensure!(
                paragraph.is_none() || depth == 1,
                "Image paragraph requires a top-level body image"
            );
            ensure!(
                dimensions.is_none() || depth == 1,
                "Explicit image dimensions require a top-level body image"
            );
            let src = node
                .attrs
                .get("src")
                .and_then(Value::as_str)
                .context("Image requires embedded PNG/JPEG src")?;
            ensure!(
                (src.starts_with("data:image/png;base64,")
                    || src.starts_with("data:image/jpeg;base64,"))
                    && src.len() <= 12 * 1024 * 1024,
                "Only embedded PNG/JPEG images within limits are supported"
            );
            if dimensions.is_some() || paragraph.is_some() {
                let (header, encoded) = src.split_once(',').context("Invalid embedded image")?;
                let mime = header
                    .strip_prefix("data:")
                    .and_then(|header| header.strip_suffix(";base64"))
                    .context("Invalid embedded image MIME")?;
                let bytes = base64::engine::general_purpose::STANDARD
                    .decode(encoded)
                    .context("Invalid image base64")?;
                validate_image_display_media(mime, &bytes)?;
            }
            for key in ["alt", "title"] {
                if let Some(value) = node.attrs.get(key).filter(|v| !v.is_null()) {
                    ensure!(value.as_str().is_some_and(xml_text), "Invalid image {key}");
                }
            }
            ensure!(
                node.attrs.get("width").is_none_or(Value::is_null)
                    && node.attrs.get("height").is_none_or(Value::is_null),
                "Pixel image width/height are unsupported; use paired display EMU dimensions"
            );
        }
        if node.kind == "orderedList" {
            ensure!(
                (1..=1000000).contains(&integer(node, "start", 1)?),
                "List start is out of range"
            );
            ensure!(
                node.attrs.get("type").is_none_or(Value::is_null),
                "Custom list numbering is not supported"
            );
        }
        if matches!(node.kind.as_str(), "tableCell" | "tableHeader") {
            ensure!(
                integer(node, "colspan", 1)? == 1 && integer(node, "rowspan", 1)? == 1,
                "Merged table cells are not supported yet"
            );
            ensure!(
                node.attrs.get("colwidth").is_none_or(Value::is_null),
                "Cell colwidth is unsupported; use table columnWidthsTwips"
            );
            ensure!(
                node.attrs.get("align").is_none_or(Value::is_null),
                "Custom cell alignment is not supported yet"
            );
        }
        let positioned = node.kind == "table" && {
            let (alignment, indent) = table_position(node)?;
            alignment.is_some() || indent.is_some()
        };
        let fixed = node.kind == "table" && (table_column_widths(node)?.is_some() || positioned);
        if node.kind == "table" {
            ensure!(
                !(fixed_ancestor || fixed && table_depth > 0),
                "Explicit table geometry does not support nested tables"
            );
            let columns = node.content[0].content.len();
            ensure!(
                columns > 0 && columns <= 50 && node.content.len() <= 500,
                "Table size exceeds limits"
            );
            ensure!(
                node.content.iter().all(|row| row.content.len() == columns),
                "Table must be rectangular"
            );
        }
        for child in &node.content {
            visit(
                child,
                depth + 1,
                table_depth + usize::from(node.kind == "table"),
                fixed_ancestor || fixed,
                nodes,
                text_bytes,
            )?;
        }
        Ok(())
    }
    visit(doc, 0, 0, false, &mut nodes, &mut text_bytes)?;
    // A size edit must not create a valid-looking draft which later fails the
    // existing writer's media-count/aggregate limits. Preserve the historical
    // validation route for documents with no explicit image dimensions.
    let mut stack = vec![doc];
    let mut images = Vec::new();
    while let Some(node) = stack.pop() {
        if node.kind == "image" {
            images.push(node);
        }
        stack.extend(&node.content);
    }
    if page.is_some()
        || images.iter().any(|node| {
            node.attrs.contains_key("displayWidthEmu") || node.attrs.contains_key("imageParagraph")
        })
    {
        ensure!(images.len() <= 100, "Image count exceeds 100");
        let mut total = 0usize;
        for image in images {
            let source = image.attrs["src"].as_str().expect("validated image source");
            let encoded = source.split_once(',').context("Invalid embedded image")?.1;
            let bytes = base64::engine::general_purpose::STANDARD
                .decode(encoded)
                .context("Invalid image base64")?;
            total += bytes.len();
            ensure!(
                bytes.len() <= 8 * 1024 * 1024 && total <= 20 * 1024 * 1024,
                "Image data exceeds limits"
            );
        }
    }
    if let Some(page) = page {
        validate_page_content(doc, &page)?;
    }
    Ok(())
}

#[derive(Default)]
struct Writer {
    profile: StyleProfile,
    page: Option<PageGeometry>,
    media: Vec<(String, Vec<u8>)>,
    image_rels: Vec<String>,
    image_styles: Vec<String>,
    link_rels: Vec<String>,
    nums: Vec<String>,
    has_spacing: bool,
    image_bytes: usize,
}
impl Writer {
    fn paragraph(&mut self, node: &Node, number: Option<(usize, usize)>) -> Result<String> {
        let mut props = String::new();
        if node.kind == "heading" {
            props.push_str(&format!(
                "<w:pStyle w:val=\"Heading{}\"/>",
                integer(node, "level", 1)?
            ));
        }
        if let Some((num, level)) = number {
            props.push_str(&format!(
                "<w:numPr><w:ilvl w:val=\"{level}\"/><w:numId w:val=\"{num}\"/></w:numPr>"
            ));
        }
        if let Some(alignment) = node.attrs.get("textAlign").and_then(Value::as_str) {
            let alignment = if alignment == "justify" {
                "both"
            } else {
                alignment
            };
            props.push_str(&format!("<w:jc w:val=\"{alignment}\"/>"));
        }
        let mut spacing = String::new();
        for (key, attribute) in [
            ("spaceBefore", "before"),
            ("spaceAfter", "after"),
            ("lineSpacing", "line"),
        ] {
            if let Some(value) = node.attrs.get(key).and_then(Value::as_u64) {
                spacing.push_str(&format!(" w:{attribute}=\"{value}\""));
            }
        }
        if node.attrs.contains_key("lineSpacing") {
            spacing.push_str(" w:lineRule=\"auto\"");
        }
        if !spacing.is_empty() {
            self.has_spacing = true;
            props.push_str(&format!("<w:spacing{spacing}/>"));
        }
        let mut body = String::new();
        for child in &node.content {
            if child.kind == "hardBreak" {
                body.push_str("<w:r><w:br/></w:r>");
                continue;
            }
            let mut marks = String::new();
            let link = child.marks.iter().find(|m| m.kind == "link");
            let has_text_color = child.marks.iter().any(|mark| mark.kind == "textColor");
            let has_font_family = child.marks.iter().any(|mark| mark.kind == "fontFamily");
            if let Some(link) = link {
                let id = self.link_rels.len() + 1;
                let href = link.attrs["href"].as_str().expect("validated link");
                self.link_rels.push(format!("<Relationship Id=\"link{id}\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink\" Target=\"{}\" TargetMode=\"External\"/>", escaped(href)));
                body.push_str(&format!("<w:hyperlink r:id=\"link{id}\">"));
                if !has_text_color {
                    marks.push_str("<w:color w:val=\"0563C1\"/>");
                }
                marks.push_str("<w:u w:val=\"single\"/>");
            }
            for mark in &child.marks {
                if mark.kind == "fontSize" {
                    let half_points = mark.attrs["halfPoints"]
                        .as_u64()
                        .expect("validated font size");
                    marks.push_str(&format!(
                        "<w:sz w:val=\"{half_points}\"/><w:szCs w:val=\"{half_points}\"/>"
                    ));
                    continue;
                }
                if mark.kind == "textColor" {
                    let rgb = mark.attrs["rgb"].as_str().expect("validated text color");
                    marks.push_str(&format!("<w:color w:val=\"{rgb}\"/>"));
                    continue;
                }
                if mark.kind == "fontFamily" {
                    let name = escaped(mark.attrs["name"].as_str().expect("validated font family"));
                    marks.push_str(&format!("<w:rFonts w:ascii=\"{name}\" w:hAnsi=\"{name}\" w:eastAsia=\"{name}\" w:cs=\"{name}\"/>"));
                    continue;
                }
                marks.push_str(match mark.kind.as_str() {
                    "bold" if self.profile == StyleProfile::StandardV2 => "<w:b/><w:bCs/>",
                    "bold" => "<w:b/>",
                    "italic" if self.profile == StyleProfile::StandardV2 => "<w:i/><w:iCs/>",
                    "italic" => "<w:i/>",
                    "underline" => "<w:u w:val=\"single\"/>",
                    "strike" => "<w:strike/>",
                    "superscript" => "<w:vertAlign w:val=\"superscript\"/>",
                    "subscript" => "<w:vertAlign w:val=\"subscript\"/>",
                    "code" if has_font_family => "",
                    "code" => "<w:rFonts w:ascii=\"Consolas\" w:hAnsi=\"Consolas\"/>",
                    "link" => "",
                    _ => unreachable!(),
                });
            }
            body.push_str(&format!("<w:r><w:rPr>{marks}</w:rPr>"));
            // Real Word line breaks/tabs are elements, not newline characters in w:t.
            let text = child
                .text
                .as_deref()
                .unwrap_or("")
                .replace("\r\n", "\n")
                .replace('\r', "\n");
            for (i, line) in text.split('\n').enumerate() {
                if i > 0 {
                    body.push_str("<w:br/>");
                }
                for (j, piece) in line.split('\t').enumerate() {
                    if j > 0 {
                        body.push_str("<w:tab/>");
                    }
                    body.push_str(&format!(
                        "<w:t xml:space=\"preserve\">{}</w:t>",
                        escaped(piece)
                    ));
                }
            }
            body.push_str("</w:r>");
            if link.is_some() {
                body.push_str("</w:hyperlink>");
            }
        }
        Ok(format!("<w:p><w:pPr>{props}</w:pPr>{body}</w:p>"))
    }

    fn block(&mut self, node: &Node, level: usize) -> Result<String> {
        match node.kind.as_str() {
            "pageBreak" => Ok("<w:p><w:r><w:br w:type=\"page\"/></w:r></w:p>".into()),
            "paragraph" | "heading" => self.paragraph(node, None),
            "bulletList" | "orderedList" => {
                ensure!(level < 9, "Lists support at most nine nesting levels");
                let num = self.nums.len() + 1;
                let abstract_id = usize::from(node.kind == "orderedList");
                self.nums.push(format!("<w:num w:numId=\"{num}\"><w:abstractNumId w:val=\"{abstract_id}\"/><w:lvlOverride w:ilvl=\"{level}\"><w:startOverride w:val=\"{}\"/></w:lvlOverride></w:num>", integer(node, "start", 1)?));
                let mut result = String::new();
                for item in &node.content {
                    ensure!(
                        item.content.first().is_some_and(|p| p.kind == "paragraph"),
                        "List item must begin with a paragraph"
                    );
                    for (i, child) in item.content.iter().enumerate() {
                        if i == 0 {
                            result.push_str(&self.paragraph(child, Some((num, level)))?);
                        } else {
                            result.push_str(&self.block(child, level + 1)?);
                        }
                    }
                }
                Ok(result)
            }
            "table" => {
                let columns = node.content[0].content.len();
                let fixed_widths = table_column_widths(node)?;
                let total = table_layout_width(node, self.page.as_ref())?;
                let normalized = self.page.is_some()
                    && !node.attrs.contains_key("tableAlign")
                    && !node.attrs.contains_key("tableIndentTwips");
                let widths = fixed_widths.clone().unwrap_or_else(|| {
                    (0..columns)
                        .map(|index| {
                            total / columns as u64
                                + u64::from(normalized && (index as u64) < total % columns as u64)
                        })
                        .collect()
                });
                let layout = if fixed_widths.is_some() {
                    "<w:tblLayout w:type=\"fixed\"/>"
                } else {
                    ""
                };
                let (alignment, indent) = table_position(node)?;
                let mut position = String::new();
                if let Some(alignment) = alignment {
                    position.push_str(&format!("<w:jc w:val=\"{alignment}\"/>"));
                }
                if let Some(indent) = indent {
                    position.push_str(&format!("<w:tblInd w:w=\"{indent}\" w:type=\"dxa\"/>"));
                }
                let margins = if alignment.is_some() || indent.is_some() {
                    "<w:tblCellMar><w:left w:w=\"108\" w:type=\"dxa\"/><w:right w:w=\"108\" w:type=\"dxa\"/></w:tblCellMar>"
                } else {
                    ""
                };
                let grid: String = widths
                    .iter()
                    .map(|width| format!("<w:gridCol w:w=\"{width}\"/>"))
                    .collect();
                let mut table = format!(
                    "<w:tbl><w:tblPr><w:tblW w:w=\"{total}\" w:type=\"dxa\"/>{position}<w:tblBorders><w:top w:val=\"single\" w:sz=\"4\"/><w:left w:val=\"single\" w:sz=\"4\"/><w:bottom w:val=\"single\" w:sz=\"4\"/><w:right w:val=\"single\" w:sz=\"4\"/><w:insideH w:val=\"single\" w:sz=\"4\"/><w:insideV w:val=\"single\" w:sz=\"4\"/></w:tblBorders>{layout}{margins}</w:tblPr><w:tblGrid>{grid}</w:tblGrid>"
                );
                for row in &node.content {
                    table.push_str("<w:tr>");
                    if row.content.iter().all(|c| c.kind == "tableHeader") {
                        table.push_str("<w:trPr><w:tblHeader/></w:trPr>");
                    }
                    for (cell, width) in row.content.iter().zip(&widths) {
                        table.push_str(&format!(
                            "<w:tc><w:tcPr><w:tcW w:w=\"{width}\" w:type=\"dxa\"/>{}</w:tcPr>",
                            if cell.kind == "tableHeader" {
                                "<w:shd w:fill=\"E8EEF7\"/>"
                            } else {
                                ""
                            }
                        ));
                        for block in &cell.content {
                            table.push_str(&self.block(block, level)?);
                        }
                        // OOXML requires each table cell to end with a paragraph.
                        if cell.content.last().is_some_and(|b| b.kind == "table") {
                            table.push_str("<w:p/>");
                        }
                        table.push_str("</w:tc>");
                    }
                    table.push_str("</w:tr>");
                }
                table.push_str("</w:tbl>");
                Ok(table)
            }
            "image" => self.image(node),
            other => bail!("Cannot export block: {other}"),
        }
    }

    fn image(&mut self, node: &Node) -> Result<String> {
        let src = node
            .attrs
            .get("src")
            .and_then(Value::as_str)
            .context("Image requires src")?;
        let (extension, encoded) = if let Some(data) = src.strip_prefix("data:image/png;base64,") {
            ("png", data)
        } else if let Some(data) = src.strip_prefix("data:image/jpeg;base64,") {
            ("jpeg", data)
        } else {
            bail!("Only embedded PNG/JPEG images are supported; external URLs are not fetched");
        };
        ensure!(
            encoded.len() <= 12 * 1024 * 1024 && self.media.len() < 100,
            "Image exceeds limits"
        );
        let bytes = base64::engine::general_purpose::STANDARD
            .decode(encoded)
            .context("Invalid image base64")?;
        self.image_bytes += bytes.len();
        ensure!(
            bytes.len() <= 8 * 1024 * 1024 && self.image_bytes <= 20 * 1024 * 1024,
            "Image data exceeds limits"
        );
        let format = if extension == "png" {
            image::ImageFormat::Png
        } else {
            image::ImageFormat::Jpeg
        };
        let (width, height) = image::ImageReader::with_format(Cursor::new(&bytes), format)
            .into_dimensions()
            .context("Invalid PNG/JPEG image")?;
        ensure!(
            width > 0
                && height > 0
                && width <= 20000
                && height <= 20000
                && u64::from(width) * u64::from(height) <= 40_000_000,
            "Image dimensions exceed limits"
        );
        let mut reader = image::ImageReader::with_format(Cursor::new(&bytes), format);
        let mut limits = image::Limits::default();
        limits.max_alloc = Some(180 * 1024 * 1024);
        reader.limits(limits);
        reader.decode().context("Image pixel data is invalid")?;
        ensure!(
            node.attrs.get("width").is_none_or(Value::is_null)
                && node.attrs.get("height").is_none_or(Value::is_null),
            "Pixel image width/height are unsupported; use paired display EMU dimensions"
        );
        let id = self.media.len() + 1;
        let name = format!("image{id}.{extension}");
        self.media.push((name.clone(), bytes));
        self.image_rels.push(format!("<Relationship Id=\"image{id}\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/image\" Target=\"media/{name}\"/>"));
        let scale = (600.0 / f64::from(width))
            .min(1.0)
            .min(800.0 / f64::from(height));
        let dimensions = image_display_dimensions(node)?;
        let paragraph = image_paragraph(node)?;
        let inline_attributes = if dimensions.is_some() || paragraph.is_some() {
            r#" distT="0" distB="0" distL="0" distR="0""#
        } else {
            ""
        };
        let (cx, cy) = dimensions.unwrap_or_else(|| {
            (
                (f64::from(width) * scale * 9525.0).round() as u64,
                (f64::from(height) * scale * 9525.0).round() as u64,
            )
        });
        let alt = node.attrs.get("alt").and_then(Value::as_str).unwrap_or("");
        let title = node
            .attrs
            .get("title")
            .and_then(Value::as_str)
            .unwrap_or("");
        ensure!(xml_text(alt) && xml_text(title), "Invalid image metadata");
        let mut paragraph_properties = String::new();
        let mut run_properties = String::new();
        if let Some(paragraph) = paragraph {
            self.has_spacing = true;
            let align = if paragraph.text_align == "justify" {
                "both"
            } else {
                &paragraph.text_align
            };
            if let (Some(base), Some(run)) = (&paragraph.paragraph_font, &paragraph.run_font) {
                let base = image_font_xml(base);
                run_properties = format!("<w:rPr>{}</w:rPr>", image_font_xml(run));
                self.image_styles.push(format!("<w:style w:type=\"paragraph\" w:styleId=\"ImageParagraph{id}\"><w:name w:val=\"Image Paragraph {id}\"/><w:basedOn w:val=\"Normal\"/><w:rPr>{base}</w:rPr></w:style>"));
                paragraph_properties.push_str(&format!("<w:pStyle w:val=\"ImageParagraph{id}\"/>"));
            }
            paragraph_properties.push_str(&format!("<w:spacing w:before=\"{}\" w:after=\"{}\" w:line=\"{}\" w:lineRule=\"auto\"/><w:jc w:val=\"{align}\"/>", paragraph.space_before, paragraph.space_after, paragraph.line_spacing));
            paragraph_properties = format!("<w:pPr>{paragraph_properties}</w:pPr>");
        }
        Ok(format!(
            r#"<w:p>{paragraph_properties}<w:r>{run_properties}<w:drawing><wp:inline{inline_attributes}><wp:extent cx="{cx}" cy="{cy}"/><wp:docPr id="{id}" name="image{id}" descr="{}" title="{}"/><wp:cNvGraphicFramePr/><a:graphic><a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/picture"><pic:pic><pic:nvPicPr><pic:cNvPr id="0" name="{name}"/><pic:cNvPicPr/></pic:nvPicPr><pic:blipFill><a:blip r:embed="image{id}"/><a:stretch><a:fillRect/></a:stretch></pic:blipFill><pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="{cx}" cy="{cy}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></pic:spPr></pic:pic></a:graphicData></a:graphic></wp:inline></w:drawing></w:r></w:p>"#,
            escaped(alt),
            escaped(title)
        ))
    }
}

fn image_font_xml(font: &crate::image_dimensions::ImageParagraphFont) -> String {
    let family = escaped(&font.family);
    let size = font.half_points;
    let bold = u8::from(font.bold);
    let italic = u8::from(font.italic);
    format!(
        r#"<w:rFonts w:ascii="{family}" w:hAnsi="{family}" w:eastAsia="{family}" w:cs="{family}"/><w:b w:val="{bold}"/><w:bCs w:val="{bold}"/><w:i w:val="{italic}"/><w:iCs w:val="{italic}"/><w:sz w:val="{size}"/><w:szCs w:val="{size}"/>"#
    )
}

fn encode_docx(doc: &Node) -> Result<(Vec<u8>, ExportReport)> {
    validate(doc)?;
    let profile = style_profile(doc)?;
    let model_part = profile.model_part();
    let mut writer = Writer {
        profile,
        page: page_geometry(doc)?,
        ..Writer::default()
    };
    let mut body = String::new();
    for block in &doc.content {
        body.push_str(&writer.block(block, 0)?);
    }
    let section = if let Some(page) = page_geometry(doc)? {
        let orientation = if page.width_twips > page.height_twips {
            r#" w:orient="landscape""#
        } else {
            ""
        };
        format!(
            r#"<w:pgSz w:w="{}" w:h="{}"{orientation}/><w:pgMar w:top="{}" w:right="{}" w:bottom="{}" w:left="{}" w:header="720" w:footer="720" w:gutter="0"/>"#,
            page.width_twips,
            page.height_twips,
            page.margin_top_twips,
            page.margin_right_twips,
            page.margin_bottom_twips,
            page.margin_left_twips
        )
    } else {
        r#"<w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440" w:header="720" w:footer="720" w:gutter="0"/>"#.to_owned()
    };
    let document = format!(
        r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" xmlns:wp="http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing" xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:pic="http://schemas.openxmlformats.org/drawingml/2006/picture"><w:body>{body}<w:sectPr>{section}</w:sectPr></w:body></w:document>"#
    );
    let mut styles = match profile {
        StyleProfile::LegacyV1 => r#"<w:styles xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:docDefaults><w:rPrDefault><w:rPr><w:rFonts w:ascii="Calibri" w:hAnsi="Calibri" w:eastAsia="Microsoft YaHei"/><w:sz w:val="22"/></w:rPr></w:rPrDefault></w:docDefaults><w:style w:type="paragraph" w:default="1" w:styleId="Normal"><w:name w:val="Normal"/></w:style>"#,
        StyleProfile::StandardV2 => r#"<w:styles xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:docDefaults><w:rPrDefault><w:rPr><w:rFonts w:ascii="Arial" w:hAnsi="Arial" w:eastAsia="Microsoft YaHei" w:cs="Arial"/><w:b w:val="0"/><w:bCs w:val="0"/><w:color w:val="000000"/><w:sz w:val="22"/><w:szCs w:val="22"/></w:rPr></w:rPrDefault><w:pPrDefault><w:pPr><w:spacing w:before="0" w:after="120" w:line="360" w:lineRule="auto"/></w:pPr></w:pPrDefault></w:docDefaults><w:style w:type="paragraph" w:default="1" w:styleId="Normal"><w:name w:val="Normal"/></w:style>"#,
    }.to_string();
    for (level, size) in [(1, 36), (2, 30), (3, 26)] {
        match profile {
            StyleProfile::LegacyV1 => styles.push_str(&format!("<w:style w:type=\"paragraph\" w:styleId=\"Heading{level}\"><w:name w:val=\"heading {level}\"/><w:basedOn w:val=\"Normal\"/><w:pPr><w:keepNext/><w:outlineLvl w:val=\"{}\"/></w:pPr><w:rPr><w:b/><w:sz w:val=\"{size}\"/></w:rPr></w:style>", level - 1)),
            StyleProfile::StandardV2 => styles.push_str(&format!("<w:style w:type=\"paragraph\" w:styleId=\"Heading{level}\"><w:name w:val=\"heading {level}\"/><w:basedOn w:val=\"Normal\"/><w:pPr><w:keepNext/><w:spacing w:before=\"240\" w:after=\"120\" w:line=\"360\" w:lineRule=\"auto\"/><w:outlineLvl w:val=\"{}\"/></w:pPr><w:rPr><w:b/><w:bCs/><w:sz w:val=\"{size}\"/><w:szCs w:val=\"{size}\"/></w:rPr></w:style>", level - 1)),
        }
    }
    styles.push_str(&writer.image_styles.concat());
    styles.push_str("</w:styles>");
    let mut numbering =
        r#"<w:numbering xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">"#
            .to_string();
    for id in 0..2 {
        numbering.push_str(&format!(
            "<w:abstractNum w:abstractNumId=\"{id}\"><w:multiLevelType w:val=\"multilevel\"/>"
        ));
        for level in 0..9 {
            let kind = if id == 0 { "bullet" } else { "decimal" };
            let text = if id == 0 {
                "•".to_string()
            } else {
                format!("%{}.", level + 1)
            };
            numbering.push_str(&format!("<w:lvl w:ilvl=\"{level}\"><w:start w:val=\"1\"/><w:numFmt w:val=\"{kind}\"/><w:lvlText w:val=\"{text}\"/><w:lvlJc w:val=\"left\"/><w:pPr><w:ind w:left=\"{}\" w:hanging=\"360\"/></w:pPr></w:lvl>", (level+1)*720));
        }
        numbering.push_str("</w:abstractNum>");
    }
    numbering.push_str(&writer.nums.concat());
    numbering.push_str("</w:numbering>");
    let mut rels = format!(
        r#"<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="styles" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/><Relationship Id="numbering" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/numbering" Target="numbering.xml"/>{}</Relationships>"#,
        format_args!(
            "{}{}",
            writer.image_rels.concat(),
            writer.link_rels.concat()
        )
    );
    let types = r#"<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Default Extension="json" ContentType="application/json"/><Default Extension="png" ContentType="image/png"/><Default Extension="jpeg" ContentType="image/jpeg"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/><Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/><Override PartName="/word/numbering.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.numbering+xml"/></Types>"#;
    // LibreOffice treats adjacent paragraph gaps differently when the settings
    // part is absent. Activate only for the new optional spacing model, keeping
    // historical V1/V2 package bytes unchanged when no spacing is authored.
    let types = if writer.has_spacing {
        rels = rels.replace("</Relationships>", r#"<Relationship Id="settings" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/settings" Target="settings.xml"/></Relationships>"#);
        types.replace("</Types>", r#"<Override PartName="/word/settings.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.settings+xml"/></Types>"#)
    } else {
        types.to_owned()
    };
    let package_rels = format!(
        r#"<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="office" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/><Relationship Id="authoring" Type="urn:rust-wps:authoring-model" Target="{model_part}"/></Relationships>"#
    );
    let mut bytes = Cursor::new(Vec::new());
    {
        let mut hashes = std::collections::BTreeMap::new();
        let mut zip = ZipWriter::new(&mut bytes);
        for (name, data) in [
            ("[Content_Types].xml", types.as_str()),
            ("_rels/.rels", package_rels.as_str()),
            ("word/document.xml", &document),
            ("word/styles.xml", &styles),
            ("word/numbering.xml", &numbering),
            ("word/_rels/document.xml.rels", &rels),
        ] {
            zip.start_file(name, SimpleFileOptions::default())?;
            zip.write_all(data.as_bytes())?;
            hashes.insert(
                name.to_string(),
                format!("{:x}", Sha256::digest(data.as_bytes())),
            );
        }
        if writer.has_spacing {
            let data = r#"<w:settings xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"/>"#;
            zip.start_file("word/settings.xml", SimpleFileOptions::default())?;
            zip.write_all(data.as_bytes())?;
            hashes.insert(
                "word/settings.xml".into(),
                format!("{:x}", Sha256::digest(data.as_bytes())),
            );
        }
        for (name, data) in &writer.media {
            zip.start_file(format!("word/media/{name}"), SimpleFileOptions::default())?;
            zip.write_all(data)?;
            hashes.insert(
                format!("word/media/{name}"),
                format!("{:x}", Sha256::digest(data)),
            );
        }
        let embedded = serde_json::to_vec(&EmbeddedModel {
            version: profile.version(),
            document: doc.clone(),
            hashes,
        })?;
        ensure!(
            embedded.len() <= 32 * 1024 * 1024,
            "Embedded model exceeds limits"
        );
        zip.start_file(model_part, SimpleFileOptions::default())?;
        zip.write_all(&embedded)?;
        zip.finish()?;
    }
    office_oxide::Document::from_reader(
        Cursor::new(bytes.get_ref().clone()),
        office_oxide::DocumentFormat::Docx,
    )
    .context("Generated DOCX cannot be reopened")?;
    let report = ExportReport { blocks: doc.content.len(), images: writer.media.len(), bytes: bytes.get_ref().len(), warnings: vec!["Basic document export; Word/WPS pagination and font substitution require visual verification".into()] };
    Ok((bytes.into_inner(), report))
}

pub fn export_docx(doc: &Node, output: &Path) -> Result<ExportReport> {
    ensure!(
        output
            .extension()
            .is_some_and(|s| s.eq_ignore_ascii_case("docx")),
        "Output must be DOCX"
    );
    ensure!(
        !output.try_exists()?,
        "Output already exists; choose a new file"
    );
    let (bytes, report) = encode_docx(doc)?;
    let parent = output
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let mut temp = tempfile::NamedTempFile::new_in(parent)?;
    temp.write_all(&bytes)?;
    temp.as_file().sync_all()?;
    temp.persist_noclobber(output)
        .map_err(|e| anyhow::anyhow!("Cannot publish output: {}", e.error))?;
    Ok(report)
}

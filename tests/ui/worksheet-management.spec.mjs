test('worksheet prefixes preserve opaque text and maintain 3D endpoints', () => {
  const names = ['Data', 'Middle', 'Last'];
  expect(rewrite('Data!A1+"Data!A1"+[Book.xlsx]Data!A1+Table[Data!A1]', names, 0, "新'表")).toBe("'新''表'!A1+\"Data!A1\"+[Book.xlsx]Data!A1+Table[Data!A1]");
  expect(rewrite("SUM('Data:Last'!A1)", names, 0)).toBe("SUM('Middle:Last'!A1)");
  expect(rewrite('SUM(Data:Last!A1)', names, 1)).toBe('SUM(Data:Last!A1)');
  expect(rewrite('Last!A1', names, 2)).toBe('#REF!A1');
  expect(rewrite('SUM(Last:Data!A1)', names, 2)).toBe("SUM('Middle:Data'!A1)");
  expect(rewrite('SUM(Data:Middle!A1)', names, 0)).toBe("SUM('Middle'!A1)");
  expect(rewrite('SUM(Data:Last!A1)', names, 0, undefined, 2)).toBe("SUM('Middle:Last'!A1)");
  expect(rewrite('SUM(Data:Last!A1)', names, 2, undefined, 0)).toBe("SUM('Data:Middle'!A1)");
  expect(rewrite('SUM(Data:Last!A1)+Data!A1', names, 0, undefined, 1)).toBe('SUM(Data:Last!A1)+Data!A1');
  expect(rewrite("'新''表'!A1", ["新'表"], 0, '中文')).toBe("'中文'!A1");
});

test('sheet and cell operations share atomic undo history', () => {
  const editor = new WorkbookEditor({ version: 1, sheets: [{ name: 'Data', cells: [] }, { name: 'Summary', cells: [{ row: 0, column: 0, content: { type: 'formula', value: 'Data!A1' } }] }] });
  const original = editor.snapshot();
  editor.addSheet('New'); editor.setCell(2, 0, 0, 'text', '001'); editor.renameSheet(0, '源表'); editor.deleteSheet(0);
  editor.setSheetHidden(1, true); editor.moveSheet(1, 0);
  expect(editor.getCell(0, 0, 0).content.value).toBe('001');
  editor.undo(); editor.undo();
  expect(editor.getCell(0, 0, 0).content.value).toBe('#REF!A1');
  const final = editor.snapshot();
  for (let i = 0; i < 4; i++) expect(editor.undo()).toBe(true);
  expect(editor.snapshot()).toEqual(original); expect(editor.dirty).toBe(false);
  for (let i = 0; i < 4; i++) expect(editor.redo()).toBe(true);
  expect(editor.snapshot()).toEqual(final);
  const directory = mkdtempSync(path.resolve('tmp/spreadsheets/sheets-'));
  const input = path.join(directory, 'model.json'), output = path.join(directory, 'sheets.xlsx');
  writeFileSync(input, JSON.stringify(final));
  const exe = path.resolve('target/debug/rust-wps.exe');
  execFileSync(exe, ['create-xlsx', input, output], { windowsHide: true });
  const canonical = structuredClone(final);
  for (const sheet of canonical.sheets) for (const cell of sheet.cells) cell.number_format ??= null;
  expect(JSON.parse(execFileSync(exe, ['read-xlsx-model', output], { encoding: 'utf8', windowsHide: true }))).toEqual(canonical);
  const before = editor.snapshot();
  for (const name of ['New', 'bad/name', '', "'bad"]) expect(() => editor.renameSheet(0, name)).toThrow();
  expect(editor.snapshot()).toEqual(before);
  const single = new WorkbookEditor({ version: 1, sheets: [{ name: 'Only', cells: [] }] });
  expect(() => single.deleteSheet(0)).toThrow(); expect(single.canUndo).toBe(false);
  const hidden = new WorkbookEditor({ version: 1, sheets: [{ name: 'Visible', cells: [] }, { name: 'Hidden', hidden: true, cells: [] }] });
  expect(() => hidden.deleteSheet(0)).toThrow(); expect(hidden.canUndo).toBe(false);
  expect(() => hidden.setSheetHidden(0, true)).toThrow(); expect(hidden.canUndo).toBe(false);
  expect(() => hidden.moveSheet(0, 2)).toThrow();
  hidden.setSheetHidden(1, false); hidden.setSheetHidden(0, true); hidden.moveSheet(1, 0);
  const reordered = hidden.snapshot();
  expect(reordered.sheets.map(sheet => [sheet.name, sheet.hidden])).toEqual([['Hidden', false], ['Visible', true]]);
  const full = new WorkbookEditor({ version: 1, sheets: Array.from({ length: 100 }, (_, i) => ({ name: `S${i}`, cells: [] })) });
  expect(() => full.addSheet('Extra')).toThrow(); expect(full.sheetCount).toBe(100); expect(full.canUndo).toBe(false);
  const malformed = new WorkbookEditor({ version: 1, sheets: [{ name: 'Data', cells: [{ row: 0, column: 0, content: { type: 'formula', value: 'Data!A1+"unclosed' } }] }] });
  const intact = malformed.snapshot(); expect(() => malformed.renameSheet(0, 'Renamed')).toThrow();
  expect(malformed.snapshot()).toEqual(intact); expect(malformed.canUndo).toBe(false);
});

test('moved endpoints and visibility survive Rust export and independent reading', () => {
  const editor = new WorkbookEditor({ version: 1, sheets: ['A', 'B', 'C'].map(name => ({ name, cells: name === 'B' ? [{ row: 0, column: 0, content: { type: 'formula', value: 'SUM(A:C!A2)' } }] : [] })) });
  editor.setSheetHidden(2, true); editor.moveSheet(0, 2);
  expect(editor.snapshot().sheets.map(sheet => sheet.name)).toEqual(['B', 'C', 'A']);
  expect(editor.getCell(0, 0, 0).content.value).toBe("SUM('B:C'!A2)");
  const directory = mkdtempSync(path.resolve('tmp/spreadsheets/order-'));
  const input = path.join(directory, 'model.json'), output = path.join(directory, 'order.xlsx');
  writeFileSync(input, JSON.stringify(editor.snapshot()));
  execFileSync(path.resolve('target/debug/rust-wps.exe'), ['create-xlsx', input, output], { windowsHide: true });
  const python = path.join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/python/python.exe');
  const report = JSON.parse(execFileSync(python, ['-c', 'import openpyxl,json,sys; w=openpyxl.load_workbook(sys.argv[1]); print(json.dumps({"names":w.sheetnames,"states":[s.sheet_state for s in w],"formula":w["B"]["A1"].value}))', output], { encoding: 'utf8', windowsHide: true }));
  expect(report).toEqual({ names: ['B', 'C', 'A'], states: ['visible', 'hidden', 'visible'], formula: "=SUM('B:C'!A2)" });
  editor.undo(); expect(editor.getCell(1, 0, 0).content.value).toBe('SUM(A:C!A2)');
});

